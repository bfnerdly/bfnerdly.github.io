"""Write _includes/dots.html: a static point cloud of the four behavior-map clusters, used as the
inner-page header graphic. The page's own cluster (front matter `cluster: c2`) is lit by CSS.

Deterministic (seed 21). Re-run after changing _data/clusters.yml:  python3 tools/make_dots.py
"""
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
W, H = 560, 400
# Same arrangement as the home map, re-centred into this panel.
CLUSTERS = {
    "c1": (0.38, 0.36, 0.13, 70),
    "c2": (0.76, 0.62, 0.10, 54),
    "c3": (0.30, 0.76, 0.10, 46),
    "c4": (0.76, 0.22, 0.08, 38),
}
rng = np.random.default_rng(21)

parts = []
for cid, (cx, cy, s, n) in CLUSTERS.items():
    pts = []
    for k in range(3):
        ox, oy = rng.normal(0, s * 0.45, 2)
        m = n // 3
        xs = rng.normal(cx + ox, s * (0.55 + 0.3 * rng.random()), m)
        ys = rng.normal(cy + oy, s * (0.45 + 0.3 * rng.random()), m)
        pts += list(zip(xs, ys))
    circles = "".join(
        f'<circle cx="{x * W:.1f}" cy="{y * H:.1f}" r="{rng.uniform(1.4, 2.6):.1f}"/>'
        for x, y in pts if 0.02 < x < 0.98 and 0.03 < y < 0.97
    )
    parts.append(f'<g class="d-{cid}">{circles}</g>')

ghost = "".join(
    f'<circle cx="{x * W:.1f}" cy="{y * H:.1f}" r="1.1"/>'
    for x, y in rng.uniform(0.02, 0.98, (60, 2))
)
svg = (
    "{%- comment -%} Generated by tools/make_dots.py; edit that script, not this file. {%- endcomment -%}\n"
    f'<svg class="page-head__dots" data-here="{{{{ page.cluster }}}}" viewBox="0 0 {W} {H}" '
    'preserveAspectRatio="xMaxYMid meet" aria-hidden="true" focusable="false">'
    f'<g class="d-ghost">{ghost}</g>{"".join(parts)}</svg>\n'
)
(ROOT / "_includes" / "dots.html").write_text(svg, encoding="utf-8")
print("wrote _includes/dots.html")
